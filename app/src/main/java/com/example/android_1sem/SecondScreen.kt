import androidx.compose.ui.text.input.VisualTransformation

@Composable
fun SecondScreen(
    email: String,
    password: String,
    generatedPassword: String,
    onBack: () -> Unit
) {
    val passwordMatches = password == generatedPassword
    var showGenerated by remember { mutableStateOf(false) }
    val clipboard = LocalClipboardManager.current

    val equalPasswords = stringResource(R.string.equal_password)
    val notEqualPasswords = stringResource(R.string.not_equal_password)
    val show = stringResource(R.string.show)
    val hide = stringResource(R.string.hide)
    val correctPic = stringResource(R.string.correctPic)
    val incorrectPic = stringResource(R.string.incorrectPic)


    Column (
        horizontalAlignment = Alignment.CenterHorizontally,
        verticalArrangement = Arrangement.Center,
        modifier = Modifier.fillMaxSize()
            .padding(24.dp)
    ) {
        AsyncImage(
            model = if (passwordMatches) correctPic else incorrectPic,
            contentDescription = if (passwordMatches) equalPasswords else notEqualPasswords,
            Modifier.fillMaxWidth()
            )

        Text(
            text = if (passwordMatches) equalPasswords else notEqualPasswords)

        Row(
            modifier = Modifier.fillMaxWidth(),
            verticalAlignment = Alignment.CenterVertically
        ) {
            OutlinedTextField(
                value = generatedPassword,
                onValueChange = { },
                label = {
                    Text(stringResource(R.string.generated_password))
                },
                visualTransformation = if (showGenerated)
                    VisualTransformation.None
                else
                    PasswordVisualTransformation(),
                modifier = Modifier.weight(1f)
            )

            Button(onClick = { showGenerated = !showGenerated }) {
                Text(if (showGenerated) hide else show)
            }
        }

        Button(onClick = { onBack() },
            modifier = Modifier.fillMaxWidth()) {
            Text(stringResource(R.string.back))
        }

        Button(onClick = {
            clipboard.setText(AnnotatedString(generatedPassword))
        },
            modifier = Modifier.fillMaxWidth()) {
            Text(stringResource(R.string.generated_password))
        }
    }
}